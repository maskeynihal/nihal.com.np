/**
 * Builds the self-hosted web fonts (`pnpm fonts`).
 *
 * Sources (OFL variable TTFs, committed) -> assets/fonts-src/
 * Outputs:
 *   public/fonts/<name>-<hash8>.woff2   subset + axis-limited woff2
 *   src/styles/fonts.generated.css      @font-face rules + metric fallbacks
 *   src/styles/fonts.manifest.json      file names / sizes for <link rel=preload>
 *
 * Deterministic: no timestamps, outputs are named by content hash and stale
 * files are removed. WONK is kept as a 0-1 range in the single Fraunces file
 * (subset-font/HarfBuzz instancer supports range limiting), so the name can
 * switch it on with font-variation-settings: 'WONK' 1.
 */
import { createHash } from 'node:crypto';
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import subsetFont from 'subset-font';
import { create } from 'fontkit';
import { copyCodePointsFor } from './copy-chars';
import frauncesMetrics from '@capsizecss/metrics/fraunces';
import jetBrainsMonoMetrics from '@capsizecss/metrics/jetBrainsMono';
import georgiaMetrics from '@capsizecss/metrics/georgia';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const srcDir = join(root, 'assets', 'fonts-src');
const outDir = join(root, 'public', 'fonts');
const cssOut = join(root, 'src', 'styles', 'fonts.generated.css');
const manifestOut = join(root, 'src', 'styles', 'fonts.manifest.json');

export const BUDGET_BYTES = 130 * 1024;

/** Latin base range; the copy-derived code points (copy-chars.ts) are added on top. */
export const UNICODE_RANGE =
  'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215';

export function toUnicodeRange(cps: Iterable<number>): string {
  const sorted = [...new Set(cps)].sort((a, b) => a - b);
  const parts: string[] = [];
  const h = (n: number) => n.toString(16).toUpperCase().padStart(4, '0');
  for (let i = 0; i < sorted.length;) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j]! + 1) j++;
    parts.push(
      j > i ? `U+${h(sorted[i]!)}-${h(sorted[j]!)}` : `U+${h(sorted[i]!)}`,
    );
    i = j + 1;
  }
  return parts.join(', ');
}

export function codepointsOf(range: string): number[] {
  const out: number[] = [];
  for (const part of range.split(',')) {
    const m = /^U\+([0-9A-F]+)(?:-([0-9A-F]+))?$/i.exec(part.trim());
    if (!m) throw new Error(`bad unicode-range part: ${part}`);
    const lo = parseInt(m[1]!, 16);
    const hi = m[2] ? parseInt(m[2], 16) : lo;
    for (let c = lo; c <= hi; c++) out.push(c);
  }
  return out;
}

type Axes = Record<
  string,
  number | { min: number; max: number; default?: number }
>;

interface FaceSpec {
  key: 'fraunces' | 'jetbrainsMono';
  family: string;
  source: string;
  prefix: string;
  axes: Axes;
  weight: string;
}

const faces: FaceSpec[] = [
  {
    key: 'fraunces',
    family: 'Fraunces',
    source: 'Fraunces[SOFT,WONK,opsz,wght].ttf',
    prefix: 'fraunces',
    axes: {
      wght: { min: 400, max: 700, default: 400 },
      opsz: { min: 14, max: 144, default: 14 },
      SOFT: 0,
      WONK: { min: 0, max: 1, default: 0 },
    },
    weight: '400 700',
  },
  {
    key: 'jetbrainsMono',
    family: 'JetBrains Mono',
    source: 'JetBrainsMono[wght].ttf',
    prefix: 'jetbrains-mono',
    axes: { wght: { min: 400, max: 600, default: 400 } },
    weight: '400 600',
  },
];

interface Metrics {
  ascent: number;
  descent: number;
  lineGap: number;
  unitsPerEm: number;
  xWidthAvg: number;
}

// Menlo is a system font and is not in the capsize collection. Values are
// from its hhea/OS2 tables (upm 2048, monospace advance 1233).
export const menloMetrics: Metrics = {
  ascent: 1901,
  descent: -483,
  lineGap: 0,
  unitsPerEm: 2048,
  xWidthAvg: 1233,
};

const pct = (n: number) => `${(Math.round(n * 10000) / 100).toFixed(2)}%`;

export function fallbackFace(
  name: string,
  local: string,
  primary: Metrics,
  fallback: Metrics,
): { css: string; sizeAdjust: number } {
  const sizeAdjust =
    primary.xWidthAvg /
    primary.unitsPerEm /
    (fallback.xWidthAvg / fallback.unitsPerEm);
  const asc = primary.ascent / primary.unitsPerEm / sizeAdjust;
  const desc = Math.abs(primary.descent) / primary.unitsPerEm / sizeAdjust;
  const gap = primary.lineGap / primary.unitsPerEm / sizeAdjust;
  const css = `@font-face {
  font-family: '${name}';
  src: ${local};
  size-adjust: ${pct(sizeAdjust)};
  ascent-override: ${pct(asc)};
  descent-override: ${pct(desc)};
  line-gap-override: ${pct(gap)};
}
`;
  return { css, sizeAdjust };
}

async function main() {
  mkdirSync(outDir, { recursive: true });
  const manifest: Record<
    string,
    { family: string; file: string; url: string; bytes: number }
  > = {};
  const keep = new Set<string>();
  let css =
    '/* Generated by scripts/fonts/build-fonts.ts (pnpm fonts). Do not edit. */\n\n';

  for (const f of faces) {
    const ttf = readFileSync(join(srcDir, f.source));
    const wanted = new Set([
      ...codepointsOf(UNICODE_RANGE),
      ...copyCodePointsFor(f.key),
    ]);
    const text = String.fromCodePoint(...[...wanted].sort((a, b) => a - b));
    const woff2 = await subsetFont(ttf, text, {
      targetFormat: 'woff2',
      variationAxes: f.axes,
    });
    // Declare exactly the code points present in the shipped file.
    const present = (create(Buffer.from(woff2)) as { characterSet: number[] })
      .characterSet;
    const range = toUnicodeRange(
      present.filter((c) => c >= 0x20 && c !== 0xffff),
    );
    const hash = createHash('sha256').update(woff2).digest('hex').slice(0, 8);
    const file = `${f.prefix}-${hash}.woff2`;
    writeFileSync(join(outDir, file), woff2);
    keep.add(file);
    manifest[f.key] = {
      family: f.family,
      file,
      url: `/fonts/${file}`,
      bytes: woff2.length,
    };
    css += `@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url('/fonts/${file}') format('woff2');
  unicode-range: ${range};
}

`;
  }

  css += fallbackFace(
    'Fraunces Fallback',
    "local('Georgia')",
    frauncesMetrics,
    georgiaMetrics,
  ).css;
  css += '\n';
  css += fallbackFace(
    'JetBrains Mono Fallback',
    "local('Menlo-Regular'), local('Menlo')",
    jetBrainsMonoMetrics,
    menloMetrics,
  ).css;

  for (const name of readdirSync(outDir)) {
    if (name.endsWith('.woff2') && !keep.has(name)) rmSync(join(outDir, name));
  }
  writeFileSync(cssOut, css);
  writeFileSync(manifestOut, JSON.stringify(manifest, null, 2) + '\n');

  let total = 0;
  for (const [k, v] of Object.entries(manifest)) {
    total += v.bytes;
    console.log(
      `${k.padEnd(14)} ${v.file.padEnd(32)} ${v.bytes} B (${(v.bytes / 1024).toFixed(1)} KB)`,
    );
  }
  console.log(
    `total          ${total} B (${(total / 1024).toFixed(1)} KB) / budget ${BUDGET_BYTES} B`,
  );
  if (total > BUDGET_BYTES) {
    console.error('font budget exceeded');
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await main();
}
